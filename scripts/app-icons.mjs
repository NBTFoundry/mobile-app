// Writes src/ui/appIcons.ts from the website's icons (NBTFoundry.github.io: site/icons, one
// SVG per application of the catalog, and site/assets/mark-dark.svg for NBT Manager).
//
//   yarn icons            (NBT_SITE_DIR, default ../NBTFoundry.github.io)
//
// Run it when the catalog gains an application; an application without an icon here shows
// its first letter.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const site = path.resolve(root, process.env.NBT_SITE_DIR ?? '../NBTFoundry.github.io', 'site');
const svg = file => readFileSync(file, 'utf8').replace(/<!--[\s\S]*?-->/g, '').trim();
const MAX = 8 * 1024;

const icons = {};
for (const name of readdirSync(path.join(site, 'icons')).filter(n => n.endsWith('.svg')).sort()) {
  const id = name.slice(0, -4);
  const xml = svg(path.join(site, 'icons', name));
  if (!/^[a-z0-9_-]{1,48}$/.test(id) || xml.length > MAX || !xml.startsWith('<svg')) throw new Error(`unexpected icon ${name}`);
  icons[id] = xml;
}
const mark = svg(path.join(site, 'assets', 'mark-dark.svg'));

const lines = [
  '// SPDX-License-Identifier: MPL-2.0',
  '/** Generated by scripts/app-icons.mjs from the website\'s icons: do not edit. */',
  '',
  '/** One SVG per application of the catalog, by application id. */',
  'export const APP_ICONS: Readonly<Record<string, string>> = {',
  ...Object.entries(icons).map(([id, xml]) => `  ${JSON.stringify(id)}: ${JSON.stringify(xml)},`),
  '};',
  '',
  '/** NBTFoundry\'s mark; MARK_INK is drawn in the text colour, MARK_ACCENT in the accent. */',
  `export const MARK = ${JSON.stringify(mark)};`,
  "export const MARK_INK = '#e8eef4';",
  "export const MARK_ACCENT = '#4d8fe0';",
  '',
];
writeFileSync(path.join(root, 'src/ui/appIcons.ts'), lines.join('\n'));
console.log(`${Object.keys(icons).length} icons`);
